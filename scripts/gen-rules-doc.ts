/**
 * Generates docs/rules.md from rule metadata.
 *
 *   pnpm docs:rules            write the file
 *   pnpm docs:rules --check    exit 1 if the committed file is out of date (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { caGstHstPack } from '../src/packs/ca-gst-hst/index.ts';
import { COVERAGE_FROM, RATES_SOURCE, RATE_TABLE } from '../src/packs/ca-gst-hst/rates.ts';
import type { RuleMeta } from '../src/packs/types.ts';

export const RULES_DOC_PATH = resolve(dirname(fileURLToPath(import.meta.url)), '../docs/rules.md');

const cell = (s: string): string => s.replaceAll('|', '\\|');

const tierLabel = (rule: RuleMeta): string =>
  rule.appliesFromTier === undefined
    ? 'all'
    : rule.appliesFromTier === 3
      ? '3'
      : `${rule.appliesFromTier}+`;

export function renderRulesDoc(): string {
  const pack = caGstHstPack;
  const out: string[] = [
    '# Rules',
    '',
    '<!-- Generated by scripts/gen-rules-doc.ts from rule metadata. Do not edit by hand: run `pnpm docs:rules`. -->',
    '',
    `## \`${pack.id}\` ${pack.version}`,
    '',
    pack.title,
    '',
    '**Severity policy**',
    '',
    '- **warning**: input tax credit information missing from this document. The law lets that information come from other documents, so a warning never means the invoice is illegal.',
    '- **error**: something on the invoice is wrong: a GST/HST number with a typo, amounts that do not add up, a tax rate that was not in force on the tax date (within 60 days of a rate change this is a warning instead, since either rate may apply).',
    '- **info**: background: which tier applies, or a check that was skipped and why.',
    '',
    'An invoice passes when it has no errors. Warnings do not make it fail.',
    '',
    '**Tiers** (SOR/91-45 s.3, total including tax, in CAD): tier 1 under $100; tier 2 $100 to $499.99; tier 3 $500 or more. The Tier column shows the lowest tier a rule applies to.',
    '',
    '| ID | Severity | Tier | What it checks | Legal source |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const rule of pack.rules) {
    out.push(
      `| ${rule.id} | ${rule.severity} | ${tierLabel(rule)} | ${cell(rule.title)} | ${cell(rule.citation)} |`,
    );
  }

  out.push('', '### Fix hints', '');
  for (const rule of pack.rules) out.push(`- **${rule.id}**: ${rule.fix}`);

  out.push(
    '',
    '### GST/HST rate table',
    '',
    `Source: [${RATES_SOURCE.title}](${RATES_SOURCE.url}) (Canada Revenue Agency), table "${RATES_SOURCE.table}", retrieved ${RATES_SOURCE.retrieved}. Rates are checked for invoices dated ${COVERAGE_FROM} onward. "From" is where the transcribed CRA table starts, not when the rate began; an empty "To" means the rate is still in force.`,
    '',
    '| Province or territory | Tax | Rate | From | To |',
    '| --- | --- | --- | --- | --- |',
  );
  // Merge consecutive periods with the same rate so unchanged rates appear once.
  const merged: {
    jurisdiction: string;
    type: string;
    rate: string;
    effectiveFrom: string;
    effectiveTo?: string;
  }[] = [];
  for (const e of RATE_TABLE) {
    const last = merged.at(-1);
    if (
      last &&
      last.jurisdiction === e.jurisdiction &&
      last.type === e.type &&
      last.rate === e.rate
    ) {
      if (e.effectiveTo === undefined) delete last.effectiveTo;
      else last.effectiveTo = e.effectiveTo;
    } else {
      merged.push({ ...e });
    }
  }
  for (const e of merged) {
    out.push(
      `| ${e.jurisdiction} | ${e.type} | ${e.rate}% | ${e.effectiveFrom} | ${e.effectiveTo ?? ''} |`,
    );
  }
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = renderRulesDoc();
  if (process.argv.includes('--check')) {
    let actual = '';
    try {
      actual = readFileSync(RULES_DOC_PATH, 'utf8').replaceAll('\r\n', '\n');
    } catch {
      // missing file counts as out of date
    }
    if (actual !== expected) {
      console.error('docs/rules.md is out of date. Run `pnpm docs:rules` and commit the result.');
      process.exit(1);
    }
    console.log('docs/rules.md is up to date.');
  } else {
    writeFileSync(RULES_DOC_PATH, expected);
    console.log(`wrote ${RULES_DOC_PATH}`);
  }
}
